/** The language Discord itself is displayed in. */
function discordLocale(): string {
    return document.documentElement.lang || navigator.language || "en";
}

/**
 * Reading an unset dropdown makes Vencord evaluate its labels, which are
 * translated, which asks for the language again. This breaks that loop.
 */
let resolving = false;

export function currentLocale(): string {
    return activeLocale();
}

/** Arabic reads right to left; the plugin's own windows follow it. */
export const isRightToLeft = () => activeLocale() === "ar";

function activeLocale(): string {
    if (resolving) return "en";
    resolving = true;

    try {
        const chosen = config().locale;
        const code = String(chosen && chosen !== "auto" ? chosen : discordLocale()).toLowerCase();

        // "ru", "ru-RU" and "uk-UA" all map to the same block.
        const base = code.split("-")[0];
        return STRINGS[code] ? code : STRINGS[base] ? base : "en";
    } catch {
        return "en";
    } finally {
        resolving = false;
    }
}

/**
 * A language name rarely fits a sentence in its dictionary form: Russian wants
 * the genitive, German an ending, French an article. Regular enough to derive.
 */
const NAME_SHAPE: Record<string, (name: string) => string> = {
    // арабский -> арабского, иврит -> иврита, хинди -> хинди
    ru: name => {
        if (/(ий|ый|ой)$/.test(name)) return name.replace(/..$/, "ого");
        if (/[бвгджзйклмнпрстфхцчшщ]$/i.test(name)) return name + "а";
        return name;
    },
    // арабська -> арабської, іврит -> івриту, гінді -> гінді
    uk: name => {
        if (/а$/.test(name)) return name.slice(0, -1) + "ої";
        if (/[бвгґджзйклмнпрстфхцчшщ]$/i.test(name)) return name + "у";
        return name;
    },
    // aus dem Arabischen, aus dem Hindi
    de: name => (/[aeiouäöü]$/i.test(name) ? name : name + "en"),
    // du russe, de l'arabe
    fr: name => (/^[aeiouyéèêîôh]/i.test(name) ? "de l'" : "du ") + name,
    es: name => "del " + name,
    pt: name => "do " + name,
    // dari bahasa Spanyol
    id: name => "bahasa " + name
};

/** Puts a language name into the form the interface language needs. */
export function shapeLanguageName(name: string): string {
    const shape = NAME_SHAPE[activeLocale()];
    return shape ? shape(name) : name;
}

/** Looks up a string, filling in {placeholders}. Falls back to English. */
export function t(key: string, values?: Record<string, string | number>): string {
    let text: string;

    try {
        const table = STRINGS[activeLocale()] ?? en;
        text = table[key] ?? en[key] ?? key;
    } catch {
        text = en[key] ?? key;
    }

    if (values)
        for (const [name, value] of Object.entries(values))
            text = text.replaceAll(`{${name}}`, String(value));

    return text;
}
